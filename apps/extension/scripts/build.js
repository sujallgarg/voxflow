#!/usr/bin/env node

/**
 * VoxFlow Extension Build Script
 * 
 * Supports both development and production builds with configurable API URLs.
 * 
 * Usage:
 *   node scripts/build.js            -> Development build (defaults to http://localhost:3001)
 *   node scripts/build.js --dev      -> Development build
 *   node scripts/build.js --prod     -> Production build (requires VOXFLOW_API_URL with HTTPS)
 * 
 * Environment variables:
 *   VOXFLOW_API_URL: Target backend URL (e.g., https://api.voxflow.com)
 *   VOXFLOW_ENV:     "production" | "development"
 */

import fs from "fs";
import path from "path";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const extensionRoot = path.resolve(__dirname, "..");

const args = process.argv.slice(2);
const isProdFlag = args.includes("--prod") || args.includes("--production");
const isDevFlag = args.includes("--dev") || args.includes("--development");

const envSetting = (process.env.VOXFLOW_ENV || process.env.NODE_ENV || "").toLowerCase();
const isProduction = isProdFlag || (!isDevFlag && envSetting === "production");

const rawApiUrl = (process.env.VOXFLOW_API_URL || process.env.API_URL || "").trim();

let targetApiUrl = "";

if (isProduction) {
  if (!rawApiUrl) {
    console.error("\n❌ Production Build Error: Missing target API URL.");
    console.error("   Production extension builds require a valid HTTPS API URL.");
    console.error("   Please set the VOXFLOW_API_URL environment variable.");
    console.error("\n   Example:");
    console.error("     VOXFLOW_API_URL=https://api.voxflow.com pnpm build:prod\n");
    process.exit(1);
  }

  let parsedUrl;
  try {
    parsedUrl = new URL(rawApiUrl);
  } catch {
    console.error(`\n❌ Production Build Error: Invalid URL format: "${rawApiUrl}"`);
    console.error("   URL must be a valid, fully qualified web address (e.g., https://api.voxflow.com).\n");
    process.exit(1);
  }

  if (parsedUrl.protocol !== "https:") {
    console.error(`\n❌ Production Build Error: Insecure protocol "${parsedUrl.protocol}" is not permitted.`);
    console.error("   Production builds strictly require HTTPS (https://...).");
    console.error(`   Received: ${rawApiUrl}\n`);
    process.exit(1);
  }

  if (parsedUrl.hostname === "localhost" || parsedUrl.hostname === "127.0.0.1") {
    console.error(`\n❌ Production Build Error: Production builds cannot target localhost ("${rawApiUrl}").`);
    console.error("   For local testing, use development build: pnpm build:dev\n");
    process.exit(1);
  }

  targetApiUrl = rawApiUrl.replace(/\/+$/, "");
} else {
  // Development mode
  if (rawApiUrl) {
    try {
      new URL(rawApiUrl);
      targetApiUrl = rawApiUrl.replace(/\/+$/, "");
    } catch {
      console.warn(`⚠️ Warning: Custom API URL "${rawApiUrl}" may be malformed. Using as-is.`);
      targetApiUrl = rawApiUrl.replace(/\/+$/, "");
    }
  } else {
    targetApiUrl = "http://localhost:3001";
  }
}

console.log("\n==================================================");
console.log(` VoxFlow Extension Build [${isProduction ? "PRODUCTION" : "DEVELOPMENT"}]`);
console.log(` Target API URL: ${targetApiUrl}`);
console.log("==================================================\n");

// 1. Generate src/config.ts
const configContent = `// Auto-generated by scripts/build.js. Do not edit manually.
export const API_BASE_URL = ${JSON.stringify(targetApiUrl)};
export const IS_PRODUCTION = ${JSON.stringify(isProduction)};
`;

const configPath = path.join(extensionRoot, "src", "config.ts");
fs.writeFileSync(configPath, configContent, "utf-8");
console.log("✓ Generated src/config.ts");

// 2. Run TypeScript compiler
console.log("Compiling TypeScript (tsc)...");
try {
  execSync("tsc", {
    cwd: extensionRoot,
    stdio: "inherit"
  });
  console.log("✓ TypeScript compiled to dist/");
} catch (error) {
  console.error("❌ TypeScript compilation failed.");
  process.exit(1);
}

// 3. Copy static assets to dist/
const staticFiles = [
  "src/manifest.json",
  "src/popup.html",
  "src/popup.css",
  "src/offscreen.html",
  "src/permission.html"
];

const distDir = path.join(extensionRoot, "dist");
if (!fs.existsSync(distDir)) {
  fs.mkdirSync(distDir, { recursive: true });
}

for (const relFile of staticFiles) {
  const srcPath = path.join(extensionRoot, relFile);
  const destPath = path.join(distDir, path.basename(relFile));
  if (fs.existsSync(srcPath)) {
    fs.copyFileSync(srcPath, destPath);
  } else {
    console.warn(`⚠️ Warning: ${relFile} not found to copy.`);
  }
}
console.log("✓ Static assets copied to dist/");

console.log("\n✨ VoxFlow extension build completed successfully!");
console.log(`   Output: ${path.relative(process.cwd(), distDir)}\n`);
